CREATE DATABASE IF NOT EXISTS dominando_mamografia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE dominando_mamografia;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER', is_premium TINYINT NOT NULL DEFAULT 0,
 premium_since DATETIME NULL, status TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS auth_tokens (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED PRIMARY KEY, name VARCHAR(150) NOT NULL, slug VARCHAR(190) NOT NULL UNIQUE,
 description TEXT NULL, icon VARCHAR(50) NULL, access_type ENUM('FREE','PREMIUM') NOT NULL,
 order_position INT NOT NULL DEFAULT 0, status TINYINT NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS topics (
 id INT UNSIGNED PRIMARY KEY, category_id INT UNSIGNED NOT NULL, title VARCHAR(190) NOT NULL,
 slug VARCHAR(190) NOT NULL UNIQUE, subtitle VARCHAR(255) NULL,
 access_type ENUM('FREE','PREMIUM') NOT NULL, order_position INT NOT NULL DEFAULT 0,
 status TINYINT NOT NULL DEFAULT 1, FOREIGN KEY (category_id) REFERENCES categories(id)
);
CREATE TABLE IF NOT EXISTS contents (
 id INT UNSIGNED PRIMARY KEY, topic_id INT UNSIGNED NOT NULL, source_pages VARCHAR(50) NULL,
 status TINYINT NOT NULL DEFAULT 1, FOREIGN KEY (topic_id) REFERENCES topics(id)
);
CREATE TABLE IF NOT EXISTS content_blocks (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, content_id INT UNSIGNED NOT NULL,
 type VARCHAR(40) NOT NULL, title VARCHAR(190) NULL, body LONGTEXT NULL, metadata JSON NULL,
 order_position INT NOT NULL DEFAULT 0, status TINYINT NOT NULL DEFAULT 1,
 FOREIGN KEY (content_id) REFERENCES contents(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS media (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, topic_id INT UNSIGNED NULL,
 type ENUM('IMAGE','VIDEO_UPLOAD','VIDEO_URL') NOT NULL,
 title VARCHAR(255) NOT NULL, caption TEXT NULL, alt_text VARCHAR(255) NULL,
 file_path VARCHAR(700) NULL, original_name VARCHAR(255) NULL, external_url VARCHAR(1000) NULL,
 thumbnail_path VARCHAR(700) NULL, mime_type VARCHAR(100) NULL, size BIGINT UNSIGNED NOT NULL DEFAULT 0,
 duration DECIMAL(10,2) NULL, width INT NULL, height INT NULL,
 order_position INT NOT NULL DEFAULT 0, status TINYINT NOT NULL DEFAULT 1,
 access_type ENUM('FREE','PREMIUM') NOT NULL DEFAULT 'PREMIUM',
 source_key CHAR(64) NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE SET NULL,
 INDEX media_filter (status, type, topic_id)
);
CREATE TABLE IF NOT EXISTS content_media (
 content_id INT UNSIGNED NOT NULL, media_id INT UNSIGNED NOT NULL, order_position INT NOT NULL DEFAULT 0,
 PRIMARY KEY(content_id,media_id), FOREIGN KEY(content_id) REFERENCES contents(id) ON DELETE CASCADE,
 FOREIGN KEY(media_id) REFERENCES media(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id INT UNSIGNED NOT NULL, media_id INT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,media_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(media_id) REFERENCES media(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS settings (`key` VARCHAR(100) PRIMARY KEY, value LONGTEXT NULL);
CREATE TABLE IF NOT EXISTS logs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL, action VARCHAR(100) NOT NULL,
 details JSON NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

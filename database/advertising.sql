CREATE TABLE IF NOT EXISTS partners (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, description VARCHAR(1000) NOT NULL DEFAULT '',
 website VARCHAR(1000) NOT NULL DEFAULT '', logo_path VARCHAR(200) NULL,
 status TINYINT NOT NULL DEFAULT 1, order_position INT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS banners (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, partner_id INT UNSIGNED NOT NULL,
 title VARCHAR(120) NOT NULL, description VARCHAR(300) NOT NULL DEFAULT '',
 image_path VARCHAR(200) NULL, url VARCHAR(1000) NOT NULL,
 cta VARCHAR(40) NOT NULL DEFAULT 'Saiba mais', placements JSON NOT NULL,
 start_on DATE NULL, end_on DATE NULL, status TINYINT NOT NULL DEFAULT 0,
 order_position INT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(partner_id) REFERENCES partners(id), INDEX banner_schedule(status,start_on,end_on)
);

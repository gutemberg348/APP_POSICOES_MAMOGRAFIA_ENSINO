from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'test-results';OUT.mkdir(exist_ok=True)
credentials={line.split(': ',1)[0]:line.split(': ',1)[1] for line in (ROOT/'api/storage/acesso-local.txt').read_text(encoding='utf-8').splitlines() if ': ' in line}
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://localhost/app_mamografia/preview/media',wait_until='networkidle')
    expect(page.get_by_text('77 mídias',exact=True)).to_be_visible(timeout=20000)
    page.wait_for_function("Array.from(document.querySelectorAll('img')).filter(e=>e.src.includes('mode=thumb')).slice(0,4).every(e=>e.complete&&e.naturalWidth>0)")
    page.screenshot(path=str(OUT/'app-desktop.png'),full_page=True)
    page.get_by_role('tab',name='Vídeos',exact=True).click()
    expect(page.get_by_text('15 mídias',exact=True)).to_be_visible()
    page.get_by_role('button',name='Abrir Craniocaudal (CC) · Vídeo',exact=True).click()
    page.wait_for_function("document.querySelector('video')?.readyState >= 2",timeout=30000)
    page.locator('video').evaluate('(v)=>v.play()')
    page.wait_for_function("document.querySelector('video')?.currentTime > 0.3",timeout=15000)
    page.screenshot(path=str(OUT/'app-video.png'))
    page.get_by_role('button',name='Fechar mídia',exact=True).click()
    page.get_by_role('button',name='Abrir Perfil Médio-Lateral (ML) · Vídeo',exact=True).click()
    expect(page.get_by_text('DOMINANDO A MAMOGRAFIA PREMIUM',exact=True)).to_be_visible()
    page.get_by_label('Fechar Premium',exact=True).click()
    page.get_by_role('tab',name='Imagens',exact=True).click()
    expect(page.get_by_text('62 mídias',exact=True)).to_be_visible()
    page.get_by_label('Buscar mídias',exact=True).fill('Craniocaudal')
    expect(page.get_by_text('12 mídias',exact=True)).to_be_visible()
    page.get_by_label('Limpar busca',exact=True).click()
    page.get_by_role('button',name='Abrir Craniocaudal (CC) · Imagem 1',exact=True).click()
    expect(page.get_by_text('1 / 8',exact=True)).to_be_visible()
    page.get_by_label('Ampliar imagem',exact=True).click()
    expect(page.get_by_text('150%',exact=True)).to_be_visible()
    page.get_by_role('button',name='Próxima',exact=True).click()
    expect(page.get_by_text('2 / 8',exact=True)).to_be_visible()
    page.get_by_role('button',name='Fechar mídia',exact=True).click()
    page.get_by_role('button',name='Perfil',exact=True).click()
    page.get_by_label('E-mail',exact=True).fill(credentials['Email'])
    page.get_by_label('Senha',exact=True).fill(credentials['Senha'])
    page.get_by_role('button',name='Entrar',exact=True).click()
    expect(page.get_by_text('Sua biblioteca de aprendizado',exact=True)).to_be_visible()
    page.get_by_role('tab',name='Vídeos',exact=True).click()
    page.get_by_role('button',name='Abrir Perfil Médio-Lateral (ML) · Vídeo',exact=True).click()
    page.wait_for_function("document.querySelector('video')?.readyState >= 2",timeout=30000)
    page.get_by_role('button',name='Fechar mídia',exact=True).click()
    page.get_by_role('button',name='Início',exact=True).click()
    page.get_by_text('Incidências de Rotina',exact=True).click()
    page.get_by_text('Craniocaudal (CC)',exact=True).click()
    expect(page.get_by_text('Finalidade',exact=True)).to_be_visible()
    page.screenshot(path=str(OUT/'app-conteudo.png'),full_page=True)
    # Conferência da interface estreita, sem credenciais salvas.
    mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.on('pageerror',lambda e:errors.append(str(e)))
    mobile.goto('http://localhost/app_mamografia/preview/media',wait_until='networkidle')
    expect(mobile.get_by_text('77 mídias',exact=True)).to_be_visible(timeout=20000)
    mobile.wait_for_function("Array.from(document.querySelectorAll('img')).filter(e=>e.src.includes('mode=thumb')).slice(0,2).every(e=>e.complete&&e.naturalWidth>0)")
    mobile.screenshot(path=str(OUT/'app-mobile.png'))
    assert mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Overflow na tela de celular.'
    admin=browser.new_page(viewport={'width':1440,'height':1000})
    admin.on('pageerror',lambda e:errors.append(str(e)))
    admin.goto('http://localhost/app_mamografia/admin/',wait_until='networkidle')
    admin.get_by_label('E-mail',exact=True).fill(credentials['Email'])
    admin.get_by_label('Senha',exact=True).fill(credentials['Senha'])
    admin.get_by_role('button',name='Entrar no painel').click()
    admin.get_by_role('button',name='Biblioteca de mídias',exact=True).click()
    expect(admin.get_by_role('heading',name='Biblioteca de mídias',exact=True)).to_be_visible(timeout=20000)
    admin.wait_for_function("Array.from(document.querySelectorAll('.card-image img')).slice(0,4).every(e=>e.complete&&e.naturalWidth>0)")
    admin.screenshot(path=str(OUT/'admin-desktop.png'),full_page=True)
    admin.get_by_role('button',name='Vídeos',exact=True).click()
    expect(admin.get_by_text('15 arquivos na biblioteca',exact=True)).to_be_visible()
    admin.get_by_role('button',name='Visualizar Craniocaudal (CC) · Vídeo',exact=True).click()
    admin.wait_for_function("document.querySelector('video')?.readyState >= 2",timeout=30000)
    admin.get_by_label('Fechar mídia',exact=True).click()
    admin.get_by_role('button',name='Adicionar mídia',exact=True).click()
    expect(admin.get_by_role('dialog',name='Adicionar mídia',exact=True)).to_be_visible()
    admin.get_by_role('button',name='URL externa',exact=True).click()
    expect(admin.get_by_label('URL do vídeo',exact=True)).to_be_visible()
    admin.get_by_label('Fechar editor',exact=True).click()
    admin.set_viewport_size({'width':390,'height':844})
    admin.screenshot(path=str(OUT/'admin-mobile.png'))
    assert admin.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Overflow no painel.'
    assert not errors,errors
    browser.close()
print('OK: app, galeria, zoom, vídeo em reprodução, bloqueio Premium, login de revisão, conteúdo, painel e telas estreitas. Nenhum erro JavaScript.')
